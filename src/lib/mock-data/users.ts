import type { User, UserProfile } from "@/types";
import { getAuraLevel } from "@/lib/constants/aura";

function makeUser(
  id: string,
  displayName: string,
  username: string,
  city: string,
  country: string,
  auraScore: number,
  streak: number,
  longestStreak: number,
  weeklyGain: number,
  avatarUrl: string,
  bio: string
): User {
  return {
    id,
    displayName,
    username,
    avatarUrl,
    bio,
    city,
    country,
    auraScore,
    auraLevel: getAuraLevel(auraScore),
    streakCurrent: streak,
    streakLongest: longestStreak,
    weeklyAuraGain: weeklyGain,
    privacySettings: {
      defaultVisibility: "friends",
      publicProfile: true,
      leaderboardParticipation: true,
      locationLeaderboard: true,
      friendRequests: "everyone",
    },
    createdAt: "2024-09-01T00:00:00Z",
  };
}

